/// Connection handshake / control messages that sit above [TransportClient]
/// and below the encrypted Input_Event stream (Requirements 4.2, 4.3, 4.4,
/// 4.5, 4.7, 9.1).
///
/// The C# agent (task 10.x) MUST match this layout exactly. All integers are
/// big-endian. Every message below is the body of one length-prefix frame
/// (see framing.dart). Control messages start with the marker byte `0xC0`,
/// which can never be a protocol version, so they are distinguishable from
/// Protocol_Codec bytes `[version u8][type u8]...` (version is 1) without
/// changing the codec.
///
/// ## Sequence
///
/// 1. Client -> Server  `ClientHello` (cleartext)
/// 2. Server -> Client  `ServerHello` (cleartext)
/// 3a. Paired host (`pairingRequired == 0`):
///     both sides derive a [SecureChannel] from the stored shared secret and
///     the two nonces. The client sends one encrypted Heartbeat
///     (Protocol_Codec bytes) as proof of key possession. The server replies
///     with a cleartext `PairingResult` (accepted, or rejected if the proof
///     fails). After `accepted`, both sides exchange encrypted Input_Events.
/// 3b. New host (`pairingRequired == 1`): the agent displays a 6-digit
///     Pairing_Code. The user types it in the app and the client sends
///     `PairingSubmit`; the server answers with `PairingResult`. This repeats
///     until `accepted` or `lockedOut`.
///
/// ## ClientHello (28 bytes, cleartext)
///     [0xC0][0x01]
///     [protocolVersion u8]            // ProtocolCodec.version
///     [clientNonce 16 bytes]          // random, fresh per Connection
///     [hasSecret u8]                  // 1 if the client holds a shared secret
///                                     // for this host, else 0
///     [secretFingerprint 8 bytes]     // first 8 bytes of SHA-256(sharedSecret);
///                                     // all zero when hasSecret == 0. Lets the
///                                     // agent pick the right secret.
///
/// ## ServerHello (20 bytes, cleartext)
///     [0xC0][0x02]
///     [serverNonce 16 bytes]
///     [hostOs u8]                     // 0 = macOS, 1 = Windows (Requirement 9.1)
///     [pairingRequired u8]            // 0 = fingerprint matches a paired
///                                     // client, no code needed (Req. 4.5);
///                                     // 1 = pairing code needed (Req. 4.1)
///
/// ## PairingSubmit (a SecureChannel message, see secure_channel.dart)
///     Sent in the pairing phase only. The channel is keyed with
///     `pairingSecret = SHA-256(ASCII("trackpad/v1/pairing:") || code)` where
///     `code` is the 6 ASCII digits typed by the user, and the two hello
///     nonces, role = client. Its plaintext is:
///         [0xC0][0x03][newSharedSecret 32 bytes]
///     `newSharedSecret` is random, generated by the client. The agent
///     decrypts with its displayed code; a failing GCM tag means a wrong code.
///     Each attempt uses a FRESH channel (counter restarts at 0), so the
///     agent must build a new channel per attempt. On success the secret
///     becomes the stored shared secret for later connections, and the
///     Connection continues with a new SecureChannel keyed with it (counters
///     restart at 0 for both directions).
///     Limitation: a passive eavesdropper could brute-force the 6-digit code
///     offline against a captured PairingSubmit. Use Wi-Fi TLS or an
///     out-of-band-trusted environment when pairing.
///
/// ## PairingResult (6 bytes, cleartext)
///     [0xC0][0x04]
///     [status u8]                     // see [PairingStatus]
///     [failedAttempts u8]             // consecutive incorrect codes so far
///     [lockoutSeconds u16]            // remaining lockout; 0 unless lockedOut
///     The third consecutive incorrect code yields `lockedOut` with
///     lockoutSeconds = 60 (Requirement 4.4).
///
/// ## After `accepted`
/// Frames are SecureChannel messages whose plaintext is Protocol_Codec bytes.
/// The client sends a Heartbeat at least every 3 seconds.
library;

import 'dart:typed_data';

import 'package:cryptography/cryptography.dart';

import '../storage/host_info.dart';
import 'secure_channel.dart';

/// First byte of every control message.
const int controlMarker = 0xC0;

const int msgClientHello = 0x01;
const int msgServerHello = 0x02;
const int msgPairingSubmit = 0x03;
const int msgPairingResult = 0x04;

const int fingerprintLength = 8;
const int clientHelloLength =
    3 + SecureChannel.nonceLength + 1 + fingerprintLength;
const int serverHelloLength = 2 + SecureChannel.nonceLength + 2;
const int pairingResultLength = 6;
const int pairingSecretLength = 32;

/// Status codes of a [PairingResultMessage].
enum PairingStatus { accepted, incorrectCode, lockedOut, rejected }

class ClientHello {
  ClientHello({
    required this.protocolVersion,
    required List<int> clientNonce,
    required this.hasSecret,
    required List<int> fingerprint,
  }) : clientNonce = Uint8List.fromList(clientNonce),
       fingerprint = Uint8List.fromList(fingerprint);

  final int protocolVersion;
  final Uint8List clientNonce;
  final bool hasSecret;
  final Uint8List fingerprint;

  Uint8List encode() => Uint8List.fromList([
    controlMarker,
    msgClientHello,
    protocolVersion,
    ...clientNonce,
    hasSecret ? 1 : 0,
    ...fingerprint,
  ]);

  /// Returns null if [bytes] is not a valid ClientHello.
  static ClientHello? decode(List<int> bytes) {
    if (bytes.length != clientHelloLength ||
        bytes[0] != controlMarker ||
        bytes[1] != msgClientHello) {
      return null;
    }
    final flag = bytes[3 + SecureChannel.nonceLength];
    if (flag > 1) return null;
    return ClientHello(
      protocolVersion: bytes[2],
      clientNonce: bytes.sublist(3, 3 + SecureChannel.nonceLength),
      hasSecret: flag == 1,
      fingerprint: bytes.sublist(4 + SecureChannel.nonceLength),
    );
  }
}

class ServerHello {
  ServerHello({
    required List<int> serverNonce,
    required this.hostOs,
    required this.pairingRequired,
  }) : serverNonce = Uint8List.fromList(serverNonce);

  final Uint8List serverNonce;
  final HostOS hostOs;
  final bool pairingRequired;

  Uint8List encode() => Uint8List.fromList([
    controlMarker,
    msgServerHello,
    ...serverNonce,
    hostOs.index, // 0 macOS, 1 Windows
    pairingRequired ? 1 : 0,
  ]);

  /// Returns null if [bytes] is not a valid ServerHello.
  static ServerHello? decode(List<int> bytes) {
    if (bytes.length != serverHelloLength ||
        bytes[0] != controlMarker ||
        bytes[1] != msgServerHello) {
      return null;
    }
    final os = bytes[2 + SecureChannel.nonceLength];
    final pairing = bytes[3 + SecureChannel.nonceLength];
    if (os >= HostOS.values.length || pairing > 1) return null;
    return ServerHello(
      serverNonce: bytes.sublist(2, 2 + SecureChannel.nonceLength),
      hostOs: HostOS.values[os],
      pairingRequired: pairing == 1,
    );
  }
}

class PairingResultMessage {
  const PairingResultMessage({
    required this.status,
    this.failedAttempts = 0,
    this.lockoutSeconds = 0,
  });

  final PairingStatus status;
  final int failedAttempts;
  final int lockoutSeconds;

  Uint8List encode() {
    final out = Uint8List(pairingResultLength);
    out[0] = controlMarker;
    out[1] = msgPairingResult;
    out[2] = status.index;
    out[3] = failedAttempts;
    ByteData.sublistView(out).setUint16(4, lockoutSeconds, Endian.big);
    return out;
  }

  /// Returns null if [bytes] is not a valid PairingResult.
  static PairingResultMessage? decode(List<int> bytes) {
    if (bytes.length != pairingResultLength ||
        bytes[0] != controlMarker ||
        bytes[1] != msgPairingResult ||
        bytes[2] >= PairingStatus.values.length) {
      return null;
    }
    final data = ByteData.sublistView(Uint8List.fromList(bytes));
    return PairingResultMessage(
      status: PairingStatus.values[bytes[2]],
      failedAttempts: bytes[3],
      lockoutSeconds: data.getUint16(4, Endian.big),
    );
  }
}

/// First 8 bytes of SHA-256([sharedSecret]), sent in ClientHello.
Future<Uint8List> secretFingerprint(List<int> sharedSecret) async {
  final hash = await Sha256().hash(sharedSecret);
  return Uint8List.fromList(hash.bytes.sublist(0, fingerprintLength));
}

/// The 32-byte secret keying the pairing-phase channel:
/// `SHA-256(ASCII("trackpad/v1/pairing:") || code)`.
Future<Uint8List> pairingSecretFromCode(String code) async {
  final hash = await Sha256().hash('trackpad/v1/pairing:$code'.codeUnits);
  return Uint8List.fromList(hash.bytes);
}

/// Plaintext of a PairingSubmit message (before SecureChannel encryption).
Uint8List encodePairingSubmitPlaintext(List<int> newSharedSecret) {
  if (newSharedSecret.length != pairingSecretLength) {
    throw ArgumentError('secret must be $pairingSecretLength bytes');
  }
  return Uint8List.fromList([
    controlMarker,
    msgPairingSubmit,
    ...newSharedSecret,
  ]);
}

/// Returns the new shared secret, or null if [plaintext] is not a
/// PairingSubmit.
Uint8List? decodePairingSubmitPlaintext(List<int> plaintext) {
  if (plaintext.length != 2 + pairingSecretLength ||
      plaintext[0] != controlMarker ||
      plaintext[1] != msgPairingSubmit) {
    return null;
  }
  return Uint8List.fromList(plaintext.sublist(2));
}
